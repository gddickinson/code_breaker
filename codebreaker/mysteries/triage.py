"""Round 62: triage of the leads awaiting review, so the user can review them family by family, strongest first.

Each lead in status 'needs_review' or 'promising' is put in exactly one tier, from its recorded evidence:
  A  all three gates pass (validation.verdict or its word-level equivalents), and read by eye;
  B  beats a null (p-value, Bonferroni or z) and read or checked against the scan by eye;
  C  checked by eye, statistics weaker or partial (a gate missed, 'in part', 'does not pass');
  D  machine reading or analysis lead, not checked against the scan.
Families come from the lead's origin and title (table 2119, V. T. A., L. R. G., B, Jane, C. H., documented tables ...).
Integrity checks: every lead in one tier; no lead still says 'NOT yet checked' once its transcription has been read."""
import json
import re
from collections import Counter, defaultdict

from .. import leads as L
from ..languages import ROOT

RESULT = ROOT / "data/results/review_triage.json"
REPORT = ROOT / "docs/review_queue.md"

FAMILIES = [("table 2119 correspondence", ("2119",)), ("V. T. A. and Valentin", ("V. T. A.", "vta")), ("L. R. G. 1879-80", ("figaro lrg",)),
            ("B 1882-86", ("figaro b",)), ("Jane 1886", ("figaro jane",)), ("C. H. (Vigenere CEAD)", ("C. H.", "CEAD", "figaro ch")),
            ("Berthe / table 2217", ("2217",)), ("documented table 2402", ("2402",)), ("AIM dictionary code", ("Landais",)),
            ("other documented tables", ("documented table", "table 1", "table 2", "Caesar")), ("Le Figaro, other", ("figaro",))]


def family(title: str, origin: str, code: str) -> str:
    text = f"{title} {origin} {code}"
    for name, keys in FAMILIES:
        if any(k in text for k in keys):
            return name
    return "other codes"


def tier(evidence: str, detail: str) -> str:
    """Checked-by-eye and gate results are taken from the whole history; a weakness counts only if the most recent
    'Round N:' statement records it, since later rounds supersede earlier notes (Round 68)."""
    e = f"{evidence} {detail}".lower()
    parts = re.split(r"(?=round \d+)", e)
    latest = next((p for p in reversed(parts) if re.match(r"round \d+", p)), e)
    checked = any(k in e for k in ("by eye", "against the scan", "transcribed from the scan"))
    if "not yet checked" in latest:
        return "D"
    three = any(k in e for k in ("all three gates pass", "three gates pass", "passes all three gates"))
    weak = any(k in latest for k in ("does not pass", "in part", "missed", "narrowly fails", "fails (", "not all passed", "not significant", "stays in tier c"))
    strong = bool(re.search(r"p\s*[<=]+\s*\d|p=\d|bonferroni|z=\d", e))
    if checked and three and not weak:
        return "A"
    if checked and (strong or three) and not weak:
        return "B"
    if checked:
        return "C"
    return "D"


def run() -> dict:
    db = L.connect()
    rows = list(db.execute("select id, code, title, detail, evidence, status, origin from leads where status in ('needs_review', 'promising') order by id"))
    out = []
    for lid, code, title, detail, ev, status, origin in rows:
        out.append({"id": lid, "code": code, "status": status, "family": family(title, origin or "", code), "tier": tier(ev or "", detail or ""),
                    "title": title, "reading": (detail or "")[:160]})
    by = defaultdict(Counter)
    for r in out:
        by[r["family"]][r["tier"]] += 1
    stale = [r["id"] for r in out if r["tier"] == "D" and r["family"] == "table 2119 correspondence"]
    return {"id": "review_triage", "leads": len(out), "tiers": dict(Counter(r["tier"] for r in out)), "by_family": {k: dict(v) for k, v in by.items()},
            "unchecked_2119": stale, "rows": out}


def report(res: dict) -> str:
    lines = ["# Review queue", "", f"{res['leads']} leads await review (generated by `codebreaker/mysteries/triage.py`). None is claimed as solved; novelty against Didier Muller's database is unconfirmed for all.", "",
             "Tiers: **A** all three gates pass and read by eye; **B** beats a null and read by eye; **C** read by eye, statistics weaker or partial; **D** machine reading or analysis lead, not checked against the scan.", "",
             "| Family | A | B | C | D |", "|---|---|---|---|---|"]
    for fam, t in sorted(res["by_family"].items(), key=lambda x: -sum(x[1].values())):
        lines.append(f"| {fam} | {t.get('A', 0)} | {t.get('B', 0)} | {t.get('C', 0)} | {t.get('D', 0)} |")
    for t in "ABCD":
        rows = [r for r in res["rows"] if r["tier"] == t]
        lines += ["", f"## Tier {t} ({len(rows)})", ""]
        for r in rows:
            lines.append(f"- [{r['id']}] `{r['code']}` ({r['family']}): {r['reading'][:110]}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    res = run()
    RESULT.write_text(json.dumps(res, ensure_ascii=False, indent=1))
    REPORT.write_text(report(res))
    print(res["leads"], res["tiers"], res["unchecked_2119"])
    for k, v in sorted(res["by_family"].items(), key=lambda x: -sum(x[1].values())):
        print(" ", k, v)
